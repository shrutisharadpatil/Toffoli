from qiskit import QuantumCircuit
from math import pi

qc = QuantumCircuit(3)

q0 = 0
q1 = 1
q2 = 2

# -------------------------------------------------
# Initial gates
# -------------------------------------------------

qc.tdg(q0)
qc.t(q1)
qc.h(q2)

# -------------------------------------------------
# CNOT 1
# q0 -> q1
# -------------------------------------------------

qc.cx(q0, q1)

# -------------------------------------------------
# CNOT 2
# q2 -> q0
# -------------------------------------------------

qc.cx(q2, q0)

# -------------------------------------------------
# T layer
# -------------------------------------------------

qc.tdg(q0)
qc.t(q2)

# -------------------------------------------------
# Parallel CNOTs
# q1 -> q0
# q1 -> q2
# -------------------------------------------------

qc.cx(q1, q0)
qc.cx(q1, q2)

# -------------------------------------------------
# T layer
# -------------------------------------------------

qc.tdg(q0)
qc.tdg(q1)
qc.t(q2)

# -------------------------------------------------
# CNOT
# q2 -> q0
# -------------------------------------------------

qc.cx(q2, q0)

# -------------------------------------------------
# Parallel
# S on q0
# CNOT q1 -> q2
# -------------------------------------------------

qc.s(q0)
qc.cx(q1, q2)

# -------------------------------------------------
# Final
# -------------------------------------------------

qc.cx(q0, q1)
qc.h(q2)

print(qc)